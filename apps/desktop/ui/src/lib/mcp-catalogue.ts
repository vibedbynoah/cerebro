/**
 * The MCP server catalogue behind the Tools screen's "Browse servers" panel. Data only.
 *
 * Every entry is a real, published server: one of the official reference servers, or one
 * maintained by the vendor whose product it connects to. Packages and endpoints were checked
 * against their registries/docs when this file was written, and `args` are the canonical form
 * (the app wraps extensionless commands through cmd /c on Windows itself). An entry whose
 * install is `{ url }` runs on the vendor's servers over HTTP; the panel shows it but cannot
 * add it, because mcp.json here holds local (stdio) servers only.
 */

export type McpRisk = "read" | "write" | "run" | "network" | "account";

/** One environment variable the server needs. */
export interface McpEnvKey {
  /** The variable name exactly as the server reads it. */
  name: string;
  /** What to paste, shown above the field. */
  label: string;
  /** Secrets are password inputs and are not echoed anywhere else. */
  secret: boolean;
  /** Where the value comes from: a key page or the setup docs. */
  url: string;
}

/** A local process to start, or a hosted endpoint (shown as remote, not addable). */
export type McpInstall = { command: string; args: string[] } | { url: string };

export interface McpCatalogueEntry {
  id: string;
  name: string;
  category: string;
  /** One plain sentence: what the server gives a model. */
  description: string;
  install: McpInstall;
  env: readonly McpEnvKey[];
  /** The strongest thing the server can reach, read < write < run < network < account. */
  risk: McpRisk;
  /** True when the server runs entirely on this machine after install, no account or service. */
  offline: boolean;
  homepage: string;
}

