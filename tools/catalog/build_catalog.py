"""Build docs/FEATURE_CATALOG.md: the 534 Opus-reviewed features plus dated additions, numbered.

The original decisions are read unchanged from the first attempt's archive
(Projects/marrow/docs/research/2026-09/state/final__*.json), core and experimental tiers only,
deduplicated by id and never split. Additions live in docs/catalog/additions-*.json.
"""

from __future__ import annotations

import collections
import glob
import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
ARCHIVE = Path(r"C:\Users\noahm\Projects\marrow\docs\research\2026-09\state")
OUT = REPO / "docs" / "FEATURE_CATALOG.md"


def clip(s: str, n: int) -> str:
    s = " ".join(str(s or "").split())
    return s if len(s) <= n else s[: n - 1] + "…"


def main() -> None:
    sections: dict[str, list[tuple[str, str, str, str]]] = collections.defaultdict(list)
    seen: set[str] = set()
    original = 0
    for p in sorted(glob.glob(str(ARCHIVE / "final__*.json"))):
        if "competitors" in p:
            continue
        for d in json.loads(Path(p).read_text(encoding="utf-8"))["decisions"]:
            if d["id"] in seen or d["tier"] not in ("core", "experimental"):
                continue
            seen.add(d["id"])
            original += 1
            sections[d["owner_section"]].append((d["tier"], d["name"], clip(d.get("implementation"), 220), "reviewed 2026-09"))
    added = 0
    for f in sorted((REPO / "docs" / "catalog").glob("additions-*.json")):
        stamp = f.stem.removeprefix("additions-")
        for a in json.loads(f.read_text(encoding="utf-8")):
            added += 1
            sections[a["s"]].append((a["t"], a["n"], clip(a["w"], 220), f"added {stamp}"))

    total = original + added
    lines = [
        "# Cerebro feature catalog",
        "",
        f"{total} features: {original} Opus-reviewed in the first research round (kept whole, never split) "
        f"plus {added} added since. Generated by `tools/catalog/build_catalog.py`; edit the sources, not this file.",
        "Tiers: core ships in v1 behind its gate; experimental ships opt-in and labelled. Hardware-gated",
        "features are included and enabled only where the hardware supports them (docs/RESTART.md).",
        "",
    ]
    n = 0
    for sec in sorted(sections, key=lambda s: (-len(sections[s]), s)):
        items = sections[sec]
        lines += [f"## {sec} ({len(items)})", ""]
        for tier, name, what, origin in items:
            n += 1
            tag = "C" if tier == "core" else "E"
            lines.append(f"{n}. **{name}** [{tag}, {origin}] {what}")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {total} features ({original} original + {added} added) in {len(sections)} sections")


if __name__ == "__main__":
    main()
